    private void btnCrearVueloActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearVueloActionPerformed
    if (vuelo != null) {
        txInfoVuelo.setText("Atención: Ya existe un objeto Vuelo. Debe destruirlo antes de crear uno nuevo.");
        return;
    }
    try {
        String codigoVuelo = txtCodVuelo.getText().trim();
        String origen = txtOrigenVuelo.getText().trim();
        String destino = txtDestinoVuelo.getText().trim();
        String horaSalida = txtHrSalidaVuelo.getText().trim();
        String estado = (cbxEstadoVuelo.getSelectedItem() != null) ? cbxEstadoVuelo.getSelectedItem().toString() : "";
        String rutaImagen = txtRutImgVuelo.getText().trim();
        vuelo = new back_end.Vuelo(codigoVuelo, origen, destino, horaSalida, estado, rutaImagen);
        vuelo.setEstado(estado);
        vuelo.setRutaImagen(rutaImagen);
        limpiarCamposVuelo();
        txInfoVuelo.setText("Objeto Vuelo creado exitosamente.");
    } catch (IllegalArgumentException e) {
        txInfoVuelo.setText("Error de validación: " + e.getMessage());
    } catch (Exception e) {
        txInfoVuelo.setText("Error al crear Vuelo: " + e.getMessage());
    }
    }//GEN-LAST:event_btnCrearVueloActionPerformed

