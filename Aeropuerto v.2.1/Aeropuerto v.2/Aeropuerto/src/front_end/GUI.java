    private void probarPolimorfismo(Persona persona, javax.swing.JTextArea areaTexto) {
    if (persona == null) {
        areaTexto.setText("⚠️ ERROR: Primero debe crear el objeto para evaluar el polimorfismo.");
        return;
    }

    StringBuilder sb = new StringBuilder();
    sb.append("==================================================\n");
    sb.append("     DEMOSTRACIÓN DE POLIMORFISMO \n");
    sb.append("==================================================\n");
    sb.append("• Clase instanciada : ").append(persona.getClass().getSimpleName()).append("\n");
    sb.append("• Referencia utilizada   : Persona (Clase Padre)\n");
    sb.append("--------------------------------------------------\n\n");

    sb.append("1. [TOSTRING() - MOSTRAR INFORMACIÓN]:\n");// 1. MOSTRAR INFORMACIÓN (toString)
    sb.append(persona.toString()).append("\n\n");
   
    sb.append("2. [EJECUTAR ACCIÓN]:\n"); // 2. REALIZAR ACCIÓN (ejecutarAccion)
    sb.append("   ➜ ").append(persona.ejecutarAccion()).append("\n\n");

    sb.append("3. [CALCULAR RESULTADO]:\n");// 3. CALCULAR RESULTADO (calcularCostoTotal)
    sb.append("   ➜ Costo Total / Sueldo Neto: $").append(String.format("%.2f", persona.calcularCostoTotal())).append("\n\n");

    sb.append("4. [DETERMINAR CARACTERÍSTICA]:\n");// 4. DETERMINAR CARACTERÍSTICA (determinarCategoria)
    sb.append("   ➜ Categoría asignada: ").append(persona.determinarCategoria()).append("\n");
    sb.append("==================================================");

    areaTexto.setText(sb.toString());// Muestra el resultado en el JTextArea del panel correspondiente
}
