    private void btnCrearPsjActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearPsjActionPerformed
if (pasajero != null) {
        txInfoPsj.setText("¡Atención! Ya existe un Pasajero. Debe destruirlo para crear uno nuevo.");
        return;
    }
    try {
        String noPasaporte = txtNoPasaportePsj.getText();
        String asiento = txtAsientoPsj.getText();
        String nacionalidad = txtNacionalidadPsj.getText();
        String curp = txtCURPPsj.getText();
        String nombres = txtNombrePsj.getText();
        String apellidos = txtApellidosPsj.getText();
        int peso = Integer.parseInt(txtPesoPsj.getText().trim()); 
        String genero = (cbxGeneroPsj.getSelectedItem() != null) ? cbxGeneroPsj.getSelectedItem().toString() : "";
        String estadoPersona = (cbxEstadoPsj.getSelectedItem() != null) ? cbxEstadoPsj.getSelectedItem().toString() : "";
        String rutaImagen = txtRutImgPsj.getText();
        String textoFecha = txtNacimientoPsj.getText();
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd/MM/yyyy");
        sdf.setLenient(false); // Evita validar fechas inválidas (ej. 32/01/2024)
        java.util.Date nacimiento = sdf.parse(textoFecha);

        // Creación del objeto
        pasajero = new Pasajero(noPasaporte, asiento, nacionalidad, curp, nombres, apellidos, nacimiento, peso, genero, estadoPersona, rutaImagen);
        
        txInfoPsj.setText("Objeto Pasajero creado exitosamente.");
        limpiarCamposPasajero(); // pa limpiar los campos
        
    } catch (java.text.ParseException e) {
        txInfoPsj.setText("Error: La fecha de nacimiento debe tener un formato válido (dd/MM/yyyy).");
    } catch (NumberFormatException e) {
        txInfoPsj.setText("Error: El campo 'Peso' debe ser un número entero válido.");
    } catch (Exception e) {
        txInfoPsj.setText("Error al crear Pasajero: " + e.getMessage());
    }
    }//GEN-LAST:event_btnCrearPsjActionPerformed

