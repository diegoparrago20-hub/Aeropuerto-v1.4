    private boolean esFragilSeleccionado(Object itemSeleccionado) {
        if (itemSeleccionado == null) return false;
        String strVal = itemSeleccionado.toString().trim();
        return strVal.equalsIgnoreCase("true") || strVal.equalsIgnoreCase("sí") || strVal.equalsIgnoreCase("si");
    }
